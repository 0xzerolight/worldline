// Builds the site into the directory given as the first argument (default _site).
// The widget's QML JavaScript libraries are wrapped as an ES module (web/widget.js)
// so the page and the README image use exactly the widget's digits and drift.
import { readFileSync, writeFileSync, mkdirSync, copyFileSync, readdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const web = dirname(fileURLToPath(import.meta.url));
const root = dirname(web);
const out = process.argv[2] || join(root, "_site");

function wrap(name, file) {
    const src = readFileSync(join(root, "package/contents/ui", file), "utf8").replace(/^\.pragma library\s*$/m, "");
    const names = [...src.matchAll(/^(?:var|function)\s+([A-Za-z_$][\w$]*)/gm)].map(m => m[1]);
    return `// Generated by web/build.mjs from package/contents/ui/${file}; do not edit.\n` +
        `export const ${name} = (() => {\n${src.trim()}\nreturn { ${names.join(", ")} };\n})();\n`;
}

writeFileSync(join(web, "widget.js"),
    wrap("Digits", "Digits.js") + wrap("Worldline", "Worldline.js") + wrap("Palette", "Palette.js"));

const { readmeSVG } = await import("./readme-svg.js");
const { today } = await import("./today.js");

mkdirSync(out, { recursive: true });
for (const f of readdirSync(web))
    if (/\.(js|css|html)$/.test(f))
        copyFileSync(join(web, f), join(out, f));
copyFileSync(join(root, "assets/screenshot.png"), join(out, "screenshot.png"));
writeFileSync(join(out, "today.svg"), readmeSVG(today(new Date())));
